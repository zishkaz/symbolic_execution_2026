// maxTestCasesPerFunction — максимальное число тест-кейсов на одну функцию.
// Символьные циклы порождают десятки финальных состояний (по одному на каждую
// глубину развёртки), поэтому количество кейсов ограничивается: берутся
// состояния с различными path condition до достижения лимита.
const maxTestCasesPerFunction = 20

// paramBound — граница диапазона значений int-параметров, добавляемая в solver.
// Ограничение заставляет Z3 выбирать «разумные» входные значения и снижает
// риск расхождения с реальным исполнением из-за переполнения Go int.
// Если с ограничением модель не находится, выполняется повтор без него.
const paramBound = 100

// functionSignature — сигнатура анализируемой функции, извлечённая из AST
type functionSignature struct {
	name       string
	paramNames []string
	paramTypes []string // "int" или "bool" для каждого параметра
	returnType string   // "int" или "bool"
}

// testCase — один сгенерированный тест-кейс: конкретные входные значения
// параметров и ожидаемое возвращаемое значение
type testCase struct {
	pathCondition string
	args          []string // литералы аргументов в порядке параметров
	expected      string   // литерал ожидаемого результата
}

// GenerateTestFile генерирует файл с тестами для функций из переданного
// исходного файла. Для каждой функции запускается символьный анализ (Analyse),
// финальные состояния превращаются в тест-кейсы: path condition решается через
// Z3, модель даёт конкретные входные значения, ожидаемый результат — значение
// символьного return-выражения на этой модели. Файл создаётся рядом с исходным
// с суффиксом _test.go, возвращается путь к нему.
func GenerateTestFile(sourceFile string) string {
	content, err := os.ReadFile(sourceFile)
	if err != nil {
		panic(fmt.Sprintf("не удалось прочитать исходный файл %s: %v", sourceFile, err))
	}

	// Парсим AST, чтобы извлечь имя пакета и сигнатуры функций
	fset := token.NewFileSet()
	fileAST, err := parser.ParseFile(fset, sourceFile, content, 0)
	if err != nil {
		panic(fmt.Sprintf("не удалось распарсить исходный файл %s: %v", sourceFile, err))
	}

	var functions []*functionSignature
	var skipComments []string
	for _, decl := range fileAST.Decls {
		funcDecl, ok := decl.(*ast.FuncDecl)
		if !ok || funcDecl.Recv != nil {
			continue // методы и не-функции не анализируем
		}
		sig, reason := extractSignature(funcDecl)
		if reason != "" {
			skipComments = append(skipComments, fmt.Sprintf("функция %s пропущена: %s", funcDecl.Name.Name, reason))
			continue
		}
		functions = append(functions, sig)
	}

	// Для каждой функции строим тест-кейсы из результатов символьного анализа
	var testFunctions []string
	for _, sig := range functions {
		cases, reason := generateTestCases(string(content), sig)
		if len(cases) == 0 {
			skipComments = append(skipComments, fmt.Sprintf("функция %s пропущена: %s", sig.name, reason))
			continue
		}
		testFunctions = append(testFunctions, renderTestFunction(sig, cases))
	}

	// Собираем текст тестового файла
	var builder strings.Builder
	builder.WriteString("// Code generated by symbolic test generator. DO NOT EDIT.\n")
	builder.WriteString(fmt.Sprintf("package %s\n\n", fileAST.Name.Name))
	if len(testFunctions) > 0 {
		builder.WriteString("import \"testing\"\n\n")
	}
	for _, comment := range skipComments {
		builder.WriteString(fmt.Sprintf("// %s\n", comment))
		fmt.Println("GenerateTestFile:", comment)
	}
	if len(skipComments) > 0 {
		builder.WriteString("\n")
	}
	for _, testFunc := range testFunctions {
		builder.WriteString(testFunc)
		builder.WriteString("\n")
	}

	generated := []byte(builder.String())
	// Форматируем сгенерированный код; если форматирование не удалось,
	// записываем как есть (код всё равно должен компилироваться)
	if formatted, err := format.Source(generated); err == nil {
		generated = formatted
	}

	testFile := strings.TrimSuffix(sourceFile, ".go") + "_test.go"
	if err := os.WriteFile(testFile, generated, 0644); err != nil {
		panic(fmt.Sprintf("не удалось записать тестовый файл %s: %v", testFile, err))
	}
	return testFile
}

// extractSignature извлекает сигнатуру функции из AST-объявления.
// Возвращает (nil, причина), если сигнатура не поддерживается анализатором.
func extractSignature(funcDecl *ast.FuncDecl) (*functionSignature, string) {
	sig := &functionSignature{name: funcDecl.Name.Name}

	if funcDecl.Type.Params != nil {
		for _, field := range funcDecl.Type.Params.List {
			typeName, ok := supportedBasicType(field.Type)
			if !ok {
				return nil, "поддерживаются только параметры типов int и bool"
			}
			if len(field.Names) == 0 {
				return nil, "безымянные параметры не поддерживаются"
			}
			for _, name := range field.Names {
				sig.paramNames = append(sig.paramNames, name.Name)
				sig.paramTypes = append(sig.paramTypes, typeName)
			}
		}
	}

	if funcDecl.Type.Results == nil || len(funcDecl.Type.Results.List) == 0 {
		return nil, "функция без возвращаемого значения — нечего проверять в тесте"
	}
	if len(funcDecl.Type.Results.List) != 1 || len(funcDecl.Type.Results.List[0].Names) > 1 {
		return nil, "функции с несколькими возвращаемыми значениями не поддерживаются"
	}
	returnType, ok := supportedBasicType(funcDecl.Type.Results.List[0].Type)
	if !ok {
		return nil, "поддерживаются только возвращаемые значения типов int и bool"
	}
	sig.returnType = returnType

	return sig, ""
}

// supportedBasicType возвращает имя типа, если это поддерживаемый базовый тип (int или bool)
func supportedBasicType(expr ast.Expr) (string, bool) {
	ident, ok := expr.(*ast.Ident)
	if !ok || (ident.Name != "int" && ident.Name != "bool") {
		return "", false
	}
	return ident.Name, true
}

// generateTestCases запускает символьный анализ функции и строит тест-кейсы
// из финальных состояний интерпретатора. Паники анализатора на неподдерживаемых
// конструкциях перехватываются и превращаются в причину пропуска функции.
func generateTestCases(source string, sig *functionSignature) (cases []testCase, reason string) {
	defer func() {
		if r := recover(); r != nil {
			cases = nil
			reason = fmt.Sprintf("символьный анализ не поддержан: %v", r)
		}
	}()

	results := Analyse(source, sig.name)
	if len(results) == 0 {
		return nil, "символьный анализ не дал ни одного финального состояния"
	}

	// Берём состояния с различными path condition для разнообразия тестов
	seen := make(map[string]bool)
	for i := range results {
		if len(cases) >= maxTestCasesPerFunction {
			break
		}
		pcKey := results[i].PathCondition.String()
		if seen[pcKey] {
			continue
		}
		seen[pcKey] = true
		if testCase, ok := solveState(&results[i], sig); ok {
			cases = append(cases, *testCase)
		}
	}

	if len(cases) == 0 {
		return nil, "ни одно финальное состояние не удалось превратить в надёжный тест-кейс"
	}
	return cases, ""
}

// solveState превращает одно финальное состояние интерпретатора в тест-кейс:
// решает path condition через Z3, из модели извлекает конкретные значения
// параметров и вычисляет ожидаемый результат. Возвращает (nil, false), если
// состояние ненадёжно или модель построить не удалось.
func solveState(state *Interpreter, sig *functionSignature) (*testCase, bool) {
	params := make(map[string]bool, len(sig.paramNames))
	for _, name := range sig.paramNames {
		params[name] = true
	}

	// Состояния, где path condition или return-выражение содержат переменные,
	// не являющиеся параметрами, — результат грубого приближения побитовых
	// операций (интерпретатор заменяет их свежими символьными переменными).
	// Значения таких выражений не связаны со входами, поэтому тест ненадёжен.
	if containsNonParamVariable(state.PathCondition, params) {
		return nil, false
	}
	ret := state.CallStack[len(state.CallStack)-1].ReturnValue
	if ret == nil || ret.Type().String() != sig.returnType {
		return nil, false
	}
	if containsNonParamVariable(ret, params) {
		return nil, false
	}

	z3Translator := state.Analyser.Z3Translator
	ctx := z3Translator.GetContext().(*z3.Context)

	pcRaw, err := z3Translator.TranslateExpression(state.PathCondition)
	if err != nil {
		return nil, false
	}
	pc, ok := pcRaw.(z3.Bool)
	if !ok {
		return nil, false
	}

	retRaw, err := z3Translator.TranslateExpression(ret)
	if err != nil {
		return nil, false
	}
	retValue, ok := retRaw.(z3.Value)
	if !ok {
		return nil, false
	}

	// Решаем path condition: сначала с ограничением диапазона int-параметров,
	// при неудаче — без ограничения
	var model *z3.Model
	for _, bounded := range []bool{true, false} {
		solver := z3.NewSolver(ctx)
		solver.Assert(pc)
		if bounded {
			for i, name := range sig.paramNames {
				if sig.paramTypes[i] != "int" {
					continue
				}
				varRaw, err := z3Translator.TranslateExpression(symbolic.NewSymbolicVariable(name, symbolic.IntType))
				if err != nil {
					return nil, false
				}
				variable := varRaw.(z3.Int)
				solver.Assert(variable.GE(ctx.FromInt(-paramBound, ctx.IntSort()).(z3.Int)))
				solver.Assert(variable.LE(ctx.FromInt(paramBound, ctx.IntSort()).(z3.Int)))
			}
		}
		sat, err := solver.Check()
		if err != nil {
			return nil, false
		}
		if sat {
			model = solver.Model()
			break
		}
	}
	if model == nil {
		return nil, false
	}

	// Извлекаем из модели конкретные значения параметров
	args := make([]string, len(sig.paramNames))
	for i, name := range sig.paramNames {
		varRaw, err := z3Translator.TranslateExpression(symbolic.NewSymbolicVariable(name, sig.symbolicParamType(i)))
		if err != nil {
			return nil, false
		}
		literal, ok := evalLiteral(model, varRaw.(z3.Value), sig.paramTypes[i])
		if !ok {
			return nil, false
		}
		args[i] = literal
	}

	// Ожидаемый результат — значение символьного return-выражения на модели
	expected, ok := evalLiteral(model, retValue, sig.returnType)
	if !ok {
		return nil, false
	}

	return &testCase{
		pathCondition: state.PathCondition.String(),
		args:          args,
		expected:      expected,
	}, true
}

// symbolicParamType возвращает символьный тип i-го параметра
func (sig *functionSignature) symbolicParamType(i int) symbolic.ExpressionType {
	if sig.paramTypes[i] == "bool" {
		return symbolic.BoolType
	}
	return symbolic.IntType
}

// evalLiteral вычисляет Z3-выражение на модели и возвращает его как Go-литерал.
// Возвращает ("", false), если значение не является конкретным литералом
// или не помещается в int64.
func evalLiteral(model *z3.Model, value z3.Value, typeName string) (string, bool) {
	evaluated := model.Eval(value, true)
	if evaluated == nil {
		return "", false
	}
	switch typeName {
	case "int":
		intValue, ok := evaluated.(z3.Int)
		if !ok {
			return "", false
		}
		val, isLiteral, ok := intValue.AsInt64()
		if !isLiteral || !ok {
			return "", false
		}
		return fmt.Sprintf("%d", val), true
	case "bool":
		boolValue, ok := evaluated.(z3.Bool)
		if !ok {
			return "", false
		}
		val, isLiteral := boolValue.AsBool()
		if !isLiteral {
			return "", false
		}
		return fmt.Sprintf("%t", val), true
	}
	return "", false
}

// containsNonParamVariable проверяет, содержит ли выражение переменные,
// не являющиеся параметрами функции
func containsNonParamVariable(expr symbolic.SymbolicExpression, params map[string]bool) bool {
	switch e := expr.(type) {
	case *symbolic.SymbolicVariable:
		return !params[e.Name]
	case *symbolic.BinaryOperation:
		return containsNonParamVariable(e.Left, params) || containsNonParamVariable(e.Right, params)
	case *symbolic.LogicalOperation:
		for _, operand := range e.Operands {
			if containsNonParamVariable(operand, params) {
				return true
			}
		}
	case *symbolic.UnaryOperation:
		return containsNonParamVariable(e.Operand, params)
	}
	return false
}

// renderTestFunction генерирует текст теста для одной функции:
// table-driven тест для функций с параметрами, простая проверка — без них
func renderTestFunction(sig *functionSignature, cases []testCase) string {
	var builder strings.Builder

	testName := "Test" + capitalize(sig.name)
	builder.WriteString(fmt.Sprintf("// %s содержит тест-кейсы, сгенерированные по результатам символьного анализа функции %s.\n", testName, sig.name))
	builder.WriteString(fmt.Sprintf("func %s(t *testing.T) {\n", testName))

	// Функция без параметров детерминированна: достаточно одной проверки
	if len(sig.paramNames) == 0 {
		builder.WriteString(fmt.Sprintf("\tif got := %s(); got != %s {\n", sig.name, cases[0].expected))
		builder.WriteString(fmt.Sprintf("\t\tt.Errorf(\"%s() = %%v, ожидалось %s\", got)\n", sig.name, cases[0].expected))
		builder.WriteString("\t}\n")
		builder.WriteString("}\n")
		return builder.String()
	}

	builder.WriteString("\ttests := []struct {\n")
	builder.WriteString("\t\tname string\n")
	for i, name := range sig.paramNames {
		builder.WriteString(fmt.Sprintf("\t\t%s %s\n", name, sig.paramTypes[i]))
	}
	builder.WriteString(fmt.Sprintf("\t\texpected %s\n", sig.returnType))
	builder.WriteString("\t}{\n")
	for i, testCase := range cases {
		args := strings.Join(testCase.args, ", ")
		builder.WriteString(fmt.Sprintf("\t\t{\"case_%d\", %s, %s}, // path condition: %s\n", i, args, testCase.expected, testCase.pathCondition))
	}
	builder.WriteString("\t}\n")
	builder.WriteString("\tfor _, tt := range tests {\n")
	builder.WriteString("\t\tt.Run(tt.name, func(t *testing.T) {\n")

	argList := make([]string, len(sig.paramNames))
	formatVerbs := make([]string, len(sig.paramNames))
	for i, name := range sig.paramNames {
		argList[i] = "tt." + name
		formatVerbs[i] = "%v"
	}
	call := fmt.Sprintf("%s(%s)", sig.name, strings.Join(argList, ", "))
	callArgs := strings.Join(argList, ", ") + ", "
	builder.WriteString(fmt.Sprintf("\t\t\tif got := %s; got != tt.expected {\n", call))
	builder.WriteString(fmt.Sprintf("\t\t\t\tt.Errorf(\"%s(%s) = %%v, ожидалось %%v\", %sgot, tt.expected)\n",
		sig.name, strings.Join(formatVerbs, ", "), callArgs))
	builder.WriteString("\t\t\t}\n")
	builder.WriteString("\t\t})\n")
	builder.WriteString("\t}\n")
	builder.WriteString("}\n")

	return builder.String()
}

// capitalize переводит первую букву строки в верхний регистр
func capitalize(s string) string {
	r, size := utf8.DecodeRuneInString(s)
	return string(unicode.ToUpper(r)) + s[size:]
}
